#!/usr/bin/env node
// SPDX-License-Identifier: MIT
//
// Step (d) of the staging rehearsal (astra-plugins-ops
// dev/game-integrations-plan-merged.md, G3 "Done when"): sign both candidates
// and one M_REVOKE act into the games documents, OFFLINE, without the
// plugins service and without the real production signing keys.
//
// WHY THIS EXISTS, AND WHY IT IS NOT AN EDIT TO THE CATALOGUE
// -------------------------------------------------------------------------
// `bin/sign.mjs`'s CLI takes `--trust <file>` but exposes no `--roots` flag,
// so run through its CLI, `lib/trust.mjs#loadTrust` verifies that file under
// `compiledRootKeys()` -- the REAL root keys, which must never reach an
// agent's environment (CLAUDE.md, astra-plugins-ops). This script never
// calls bin/sign.mjs. Instead it imports `runSign` straight from the
// checked-out catalogue's `lib/pipeline.mjs` and calls it with the `roots`
// parameter that function already documents:
//
//   lib/pipeline.mjs:53  "`roots` is for tests only: production verifies
//                         trust.json under the compiled roots."
//
// That is not a seam this script invented -- it is the exact injection
// point the catalogue's own test suite uses (test/catalogue.mjs's
// `makeCatalogue`/`rootsOf`), reproduced here against a throwaway root key
// and throwaway `games` kind keys generated by the catalogue's own
// `bin/keygen.mjs`. Nothing in astra-games-catalogue is read, patched or
// vendored into this repository; only its already-exported `lib/*.mjs`
// functions are imported, exactly as its own tests do.
//
// Usage:
//   node dry-sign.mjs --catalogue <dir> --data <dir> --candidates <f,f,...>
//     --revoke-repo-id <id> --revoke-entry-id <id> --keys-dir <dir> --report <file>

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const args = process.argv.slice(2);
const opt = (n) => (args.indexOf(n) >= 0 ? args[args.indexOf(n) + 1] : null);

const catalogueDir = opt("--catalogue");
const dataDir = opt("--data");
const candidateFiles = (opt("--candidates") ?? "").split(",").filter(Boolean);
const revokeRepoId = Number(opt("--revoke-repo-id"));
const revokeEntryId = opt("--revoke-entry-id");
const keysDir = opt("--keys-dir");
const reportFile = opt("--report");

if (!catalogueDir || !dataDir || !candidateFiles.length || !revokeRepoId || !revokeEntryId || !keysDir || !reportFile) {
  console.error("usage: dry-sign.mjs --catalogue <dir> --data <dir> --candidates <f,f,...> --revoke-repo-id <id> --revoke-entry-id <id> --keys-dir <dir> --report <file>");
  process.exit(2);
}

// Imported straight from the checked-out catalogue -- read-only; this
// repository never edits astra-games-catalogue.
const { runSign } = await import(path.join(catalogueDir, "lib/pipeline.mjs"));
const { loadTrust } = await import(path.join(catalogueDir, "lib/trust.mjs"));
const { verifyDocuments, INDEX_SCHEMA, WITHDRAWN_SCHEMA } = await import(path.join(catalogueDir, "lib/documents.mjs"));
const { validateMany } = await import(path.join(catalogueDir, "lib/schemas.mjs"));
const {
  TRUST_SCHEMA, signEnvelope, privateKeyFromSeed, publicKeyFromBase64,
} = await import(path.join(catalogueDir, "lib/vendor/astra-registry/bot/lib/sign.mjs"));

const now = Math.floor(Date.now() / 1000);
const rfc3339 = (unixSeconds) => `${new Date(unixSeconds * 1000).toISOString().slice(0, 19)}Z`;

// ── 1. a throwaway ROOT key (never the owner's; generated and discarded in
//      this job only) ──────────────────────────────────────────────────────
function throwawayKey() {
  const { privateKey, publicKey } = crypto.generateKeyPairSync("ed25519");
  const seed = privateKey.export({ format: "der", type: "pkcs8" }).subarray(-32);
  const pub = publicKey.export({ format: "der", type: "spki" }).subarray(-32);
  return { seedB64: seed.toString("base64"), publicB64: pub.toString("base64") };
}
const rootKey = throwawayKey();

// ── 2. TEST games keys, generated by the catalogue's OWN bin/keygen.mjs
//      (never the repository's real GAMES_SIGNING_KEY_*) ───────────────────
fs.mkdirSync(keysDir, { recursive: true });
const currentSeedFile = path.join(keysDir, "current.ed25519");
const nextSeedFile = path.join(keysDir, "next.ed25519");
const keygenRow = (role, keyId, outFile, notBefore) => {
  const stdout = execFileSync("node", [
    path.join(catalogueDir, "bin/keygen.mjs"),
    "--role", role, "--key-id", keyId, "--out", outFile, "--not-before", notBefore,
  ], { encoding: "utf8" });
  return JSON.parse(stdout.trim().split("\n").pop());
};
const currentRow = keygenRow("current", "astra-games-2020a", currentSeedFile, "2020-01-01T00:00:00Z");
const nextRow = keygenRow("next", "astra-games-2020b", nextSeedFile, "2020-01-01T00:01:00Z");
console.log(`TEST games keys generated: ${currentRow.key_id} (current), ${nextRow.key_id} (next) -- private seeds stay in ${keysDir}, never printed or uploaded`);

// ── 3. a throwaway trust.json, signed by the throwaway root ───────────────
const trustSigned = {
  schema: TRUST_SCHEMA,
  serial: 1,
  issued_at: rfc3339(now - 3600),
  expires_at: rfc3339(now + 365 * 86400),
  index_keys: [],
  reusable_workflow_shas: [],
  kind_keys: [currentRow, nextRow],
};
const trustEnvelope = {
  $comment: "TEST trust.json, throwaway root -- staging rehearsal only, never published",
  ...signEnvelope({ domain: TRUST_SCHEMA, signed: trustSigned, signers: [{ key_id: "test-root", privateKey: privateKeyFromSeed(Buffer.from(rootKey.seedB64, "base64")) }] }),
};
const trustFile = path.join(keysDir, "trust.json");
fs.writeFileSync(trustFile, JSON.stringify(trustEnvelope));
const roots = { status: "test", keys: [{ key_id: "test-root", publicKey: publicKeyFromBase64(rootKey.publicB64) }] };

// ── 4. the candidates and one M_REVOKE act ─────────────────────────────────
const candidates = candidateFiles.map((f) => JSON.parse(fs.readFileSync(f, "utf8")));
const acts = [{
  schema: "astra.games.act/1",
  type: "M_REVOKE",
  at: now,
  by: { account: "mod-1" },
  confirmation: { kind: "console-2fa", ref: "dryrun-revoke-001" },
  repo_id: revokeRepoId,
  entry_id: revokeEntryId,
  versions: "*",
  reason_code: "security",
  reason_text: "Staging rehearsal: exercising a moderator revoke act in the same run as the two publishes (G3 done-when).",
}];

// ── 5. sign BOTH documents (runSign self-verifies internally; signing.mjs
//      signBoth throws SignRefused on any self-verification problem) ───────
const env = { ...process.env, GAMES_SIGNING_KEY_CURRENT: fs.readFileSync(currentSeedFile, "utf8").trim() };
delete env.GAMES_SIGNING_KEY_NEXT;
const report = runSign({ dataDir, root: catalogueDir, env, now, trustFile, roots, candidates, acts });
console.log(`runSign: issuedAt=${report.issuedAt} keyId=${report.keyId} accepted=${JSON.stringify(report.accepted.map((a) => a.result))} acts=${report.acts.length} duplicateActs=${report.duplicateActs.length} refusedActs=${report.refusedActs.length}`);
for (const r of report.refusedActs) console.error(`act refused: ${JSON.stringify(r)}`);
for (const a of report.accepted) if (a.result === "refused" || a.result === "held") console.error(`candidate not listed: ${JSON.stringify(a)}`);

// ── 6. independently re-verify the WRITTEN documents (not the in-memory
//      objects runSign already self-checked) with the catalogue's own
//      verification code, plus AstraPlugins' games schemas ────────────────
const index = JSON.parse(fs.readFileSync(path.join(dataDir, "dist", "games-index.json"), "utf8"));
const withdrawn = JSON.parse(fs.readFileSync(path.join(dataDir, "dist", "games-withdrawn.json"), "utf8"));
const { kindKeys } = loadTrust({ file: trustFile, now, roots });
const [indexProblems, withdrawnProblems] = verifyDocuments([
  { envelope: index, domain: INDEX_SCHEMA },
  { envelope: withdrawn, domain: WITHDRAWN_SCHEMA, indexBody: index.signed },
], { kindKeys, now, strict: true });

const shapeChecks = validateMany([
  { schema: "games-index-v1", doc: index.signed },
  { schema: "games-withdrawn-v1", doc: withdrawn.signed },
]);

const problems = [
  ...indexProblems.map((p) => `index/verifyDocuments: ${p}`),
  ...withdrawnProblems.map((p) => `withdrawn/verifyDocuments: ${p}`),
  ...(shapeChecks[0].ok ? [] : [`index/games-index-v1.schema.json: ${shapeChecks[0].error}`]),
  ...(shapeChecks[1].ok ? [] : [`withdrawn/games-withdrawn-v1.schema.json: ${shapeChecks[1].error}`]),
];

// ── 7. the G3 assertions: both entries in the index, the revoke in withdrawn
const indexIds = index.signed.entries.map((e) => e.id);
if (!candidates.every((c) => indexIds.includes(c.entry?.id))) {
  problems.push(`index.entries does not carry every candidate's id (has ${JSON.stringify(indexIds)})`);
}
const revokeRows = withdrawn.signed.rows.filter((r) => r.repo_id === revokeRepoId && r.act === "revoke");
if (!revokeRows.length) problems.push(`withdrawn.rows carries no revoke row for repo_id ${revokeRepoId}`);

const result = {
  ok: problems.length === 0 && report.refusedActs.length === 0 && report.accepted.every((a) => a.result !== "refused" && a.result !== "held"),
  issuedAt: report.issuedAt,
  keyId: report.keyId,
  accepted: report.accepted,
  acts: report.acts.map((a) => ({ type: a.type, seq: a.seq, confirmation_ref: a.confirmation.ref })),
  refusedActs: report.refusedActs,
  indexEntryIds: indexIds,
  withdrawnRevokeRows: revokeRows,
  problems,
};
fs.mkdirSync(path.dirname(reportFile), { recursive: true });
fs.writeFileSync(reportFile, JSON.stringify(result, null, 2));
console.log(JSON.stringify(result, null, 2));
if (!result.ok) {
  console.error("dry-sign FAILED -- see problems[] above");
  process.exit(1);
}
console.log("dry-sign OK: both candidates signed into the index, and the revoke is in the withdrawn document, in this one run.");
